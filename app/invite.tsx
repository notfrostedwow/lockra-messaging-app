import React, { useState } from 'react';
import { View, Text, StyleSheet, TouchableOpacity, TextInput, Share, ScrollView } from 'react-native';
import { useTheme } from '@/contexts/ThemeContext';
import { Stack, useRouter } from 'expo-router';
import { ChevronLeft, Share2, Copy, Mail, MessageSquare, Users } from 'lucide-react-native';
import { Button } from '@/components/ui/Button';
import { useAuth } from '@/contexts/AuthContext';
import { StatusBar } from 'expo-status-bar';

export default function InviteScreen() {
  const { colors } = useTheme();
  const router = useRouter();
  useAuth();
  const [email, setEmail] = useState('');
  const [inviteSent, setInviteSent] = useState(false);
  
  // Invite link that would be generated by the server
  const inviteLink = 'https://example.invalid';

  const handleShare = async () => {
    try {
      await Share.share({
        message: `Join me on Lockra! It's a secure messaging app where we can chat privately. Sign up using this link: ${inviteLink}`,
        title: 'Join me on Lockra',
      });
    } catch {
      console.error("Error sharing invite: [details redacted]");
    }
  };

  const handleCopyLink = () => {
    // In a real app, this would copy to clipboard
    alert('Invite link copied to clipboard!');
  };

  const handleSendEmail = () => {
    if (!email.trim()) {
      alert('Please enter an email address');
      return;
    }

    // In a real app, this would send an email invitation
    setInviteSent(true);
    setTimeout(() => setInviteSent(false), 3000);
  };

  return (
    <>
      <StatusBar style="light" />
      <Stack.Screen
        options={{
          title: 'Invite Friends',
          headerStyle: {
            backgroundColor: '#1A1D25',
          },
          headerTitleStyle: {
            color: '#FFFFFF',
          },
          headerLeft: () => (
            <TouchableOpacity
              style={styles.headerButton}
              onPress={() => router.back()}
            >
              <ChevronLeft size={24} color="#FFFFFF" />
            </TouchableOpacity>
          ),
        }}
      />
      <ScrollView style={[styles.container, { backgroundColor: '#111318' }]}>
        <View style={styles.headerSection}>
          <Users size={60} color={colors.primary} />
          <Text style={[styles.title, { color: '#FFFFFF' }]}>
            Invite Friends to Lockra
          </Text>
          <Text style={[styles.subtitle, { color: 'rgba(255, 255, 255, 0.7)' }]}>
            Share Lockra with friends and start chatting securely
          </Text>
        </View>

        <View style={[styles.card, { backgroundColor: '#1A1D25' }]}>
          <Text style={[styles.sectionTitle, { color: '#FFFFFF' }]}>
            Share Invite Link
          </Text>
          <View style={[styles.linkContainer, { backgroundColor: '#111318' }]}>
            <Text 
              style={[styles.linkText, { color: 'rgba(255, 255, 255, 0.7)' }]} 
              numberOfLines={1}
            >
              {inviteLink}
            </Text>
            <TouchableOpacity 
              style={[styles.copyButton, { backgroundColor: colors.primary }]}
              onPress={handleCopyLink}
            >
              <Copy size={16} color="white" />
              <Text style={styles.copyText}>Copy</Text>
            </TouchableOpacity>
          </View>
          
          <Button 
            title="Share Invite Link" 
            icon={<Share2 size={18} color="white" />}
            onPress={handleShare}
            style={{ marginTop: 16 }}
          />
        </View>

        <View style={[styles.card, { backgroundColor: '#1A1D25' }]}>
          <Text style={[styles.sectionTitle, { color: '#FFFFFF' }]}>
            Invite via Email
          </Text>
          <TextInput
            style={[
              styles.input, 
              { 
                backgroundColor: '#111318',
                color: '#FFFFFF',
                borderColor: 'rgba(255, 255, 255, 0.2)'
              }
            ]}
            placeholder="Enter friend's email"
            placeholderTextColor="rgba(255, 255, 255, 0.5)"
            value={email}
            onChangeText={setEmail}
            keyboardType="email-address"
            autoCapitalize="none"
          />
          <Button 
            title={inviteSent ? "Invitation Sent!" : "Send Invitation"} 
            icon={<Mail size={18} color="white" />}
            onPress={handleSendEmail}
            variant={inviteSent ? "success" : "primary"}
            style={{ marginTop: 12 }}
          />
        </View>

        <View style={[styles.card, { backgroundColor: '#1A1D25' }]}>
          <Text style={[styles.sectionTitle, { color: '#FFFFFF' }]}>
            Why Invite Friends to Lockra?
          </Text>
          
          <View style={styles.benefitItem}>
            <View style={[styles.benefitIcon, { backgroundColor: `${colors.primary}20` }]}>
              <MessageSquare size={24} color={colors.primary} />
            </View>
            <View style={styles.benefitContent}>
              <Text style={[styles.benefitTitle, { color: '#FFFFFF' }]}>
                Secure Messaging
              </Text>
              <Text style={[styles.benefitDescription, { color: '#FFFFFF' }]}>
                Offline synthetic messaging; integration and security review required
              </Text>
            </View>
          </View>
          
          <View style={styles.benefitItem}>
            <View style={[styles.benefitIcon, { backgroundColor: `${colors.primary}20` }]}>
              <Users size={24} color={colors.primary} />
            </View>
            <View style={styles.benefitContent}>
              <Text style={[styles.benefitTitle, { color: '#FFFFFF' }]}>
                Better with Friends
              </Text>
              <Text style={[styles.benefitDescription, { color: '#FFFFFF' }]}>
                The more friends you invite, the more people you can chat with
              </Text>
            </View>
          </View>
        </View>
      </ScrollView>
    </>
  );
}

